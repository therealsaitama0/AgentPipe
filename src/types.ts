/**
 * Abstract Data Type Generator v0.5.x (Rust-based)
 * 
 * This module defines standard data types compatible with C/C# syntax,
 * allowing for dynamic schema mapping and type conversion in the database generator.
 */

// -----------------------------------------------------------------------------
// Core Constants & Aliases
// -----------------------------------------------------------------------------
const ALchemySchemaMap = {
  "integer":       Number,      // Integer column definition (C-style) -> TypeScript number literal
  "string":        string,     // String column definition (C-style) -> TypeScript string literal
  "boolean":       boolean,    // Boolean column definition (C-style) -> TypeScript boolean literal
};

// -----------------------------------------------------------------------------
// Core Type Aliases Mirror C/C# Enum Semantics
// These act as Rust-like enums but are typed for compatibility with existing imports.
// They define the runtime types that can be constructed or inspected in this module.
export type AlchemyDatabaseType = string | number | boolean;

/**
 * Abstract Schema Definition (C-style) - The legacy JSON structure used by older systems
 */
interface AlchemySchema {
  [key: string]: string; // Column name -> value in C/C# style struct definition
  
  /** Key mapping from the old schema to the new type system. 
   * This allows us to treat "integer" as a TypeScript number literal,
   * while preserving its semantic meaning (e.g., casting existing JSON values). */
  [key: string]: any; // Generic key -> value in C/C# style
  
}

// -----------------------------------------------------------------------------
// Schema Conversion Functions
// These functions transform legacy AlchemySchema definitions into the abstract data types defined above.
export function schemaToType(schemaMap: AlchemySchema): Type[] {
  return Object.values(schemaMap)
    .filter((val, keyIdx) => (typeof val === "string" ? ALchemySchemaMap["integer"] : typeof val === "number" ? ALchemySchemaMap["string"] : null)) as any;
}

/**
 * Parse JSON-like schema definitions into abstract data types.
 * Handles both the legacy AlchemySchema interface and dynamic type inference from the new `AlchemyDatabaseType` defined above.
 */
export function parseSchemaToTypes(schemaMap: Record<string, string>): Type[] {
  return Object.values(schemaMap)
    .map((val): val is number => typeof val === "number" || (typeof val !== 'undefined' && typeof val !== 'string') as any);
}

/**
 * Convert an AlchemyDatabaseType back to its C/C# equivalent string representation.
 * This ensures backward compatibility when converting types generated by the system into legacy code or vice versa.
 */
export function typeToSchemaValue(type: unknown): string {
  if (type === null) return "null"; // Maps TypeScript `undefined`/`null` to C-style NULL in struct definition context
  if (typeof type === 'string') return `"${type}"`;
  if (typeof type === 'number' || typeof type === 'boolean') return `${type}`;

  throw new Error(`Unknown value: ${JSON.stringify(type)}`);
}

// -----------------------------------------------------------------------------
// Helper Functions for Type Inference & Validation
// These functions enable the system to dynamically determine types based on schema content, avoiding hard-coded assumptions.
export function inferSchemaTypeFromMap(schemaMap: AlchemySchema): "integer" | "string" | null {
  // Attempt to match against known constants first (for performance in large schemas)
  if (ALchemySchemaMap["boolean"]) return "integer"; 
  if (typeof ALchemySchemaMap["null"] === 'object') return "undefined";

  let typeStr = "";
  
  for (const [key, value] of Object.entries(schemaMap)) {
    const typeName = key.toLowerCase().replace(/[^a-z0-9]/gi, '_'); // Canonicalize keys like SchemaColumn -> column_name
    
    if (!ALchemySchemaMap[typeName]) continue;

    switch (value) {
      case "integer": typeStr += ALchemySchemaMap["string"]; break;
      case "string":   typeStr = value as string;  break;
      default:         throw new Error(`Unknown schema column '${key}' mapping to ${ALchemySchemaMap[key]} or invalid type`);
    }

    if (typeStr === null || typeStr === undefined) return null; // Silently skip unknown columns in this context, though explicit error would be better.
  }

  return "integer";
}

