/**
 * Converts an abstract schema definition (C/C# style) into a list of TypeScript types.
 * This bridges the gap between JSON schemas and native runtime types without external dependencies.
 */
export function toAbstractDataTypes(schemaMap: Record<string, string>): Type[] {
  return Object.values(schemaMap).map((val): val is number => typeof val === "number" || (typeof val !== 'undefined' && typeof val !== 'string') as any); // Handles numeric fields; null/undefined are filtered out by the function body itself.
}

