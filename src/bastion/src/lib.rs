/// Error type for security control plane operations.
#[derive(Debug, Clone)]
pub enum SecurityControlPlaneError {
    /// Failed to parse a required configuration file.
    ConfigParse(String),
    /// Authentication failed due to missing or invalid RSA keys.
    MissingKeyPair(String),
    /// Key exchange protocol mismatch detected during handshake.
    ProtocolMismatch(String, String),
}

/// Represents the current state of an authentication session within the bastion environment.
#[derive(Debug)]
pub struct Session {
    pub key_pair: PublicKeyPair, // RSA Private Key and Public Certificate/Signature for verification
    /// A mutable reference to a trusted root CA or intermediate server used in certificate revocation checks (if applicable).
    pub trust_root_ca: Option<RootCA>,
}

