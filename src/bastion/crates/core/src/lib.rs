#[derive(Debug)]
pub enum BastionError {
    /// Raised when a critical security policy fails.
    InvalidPolicy(serde_json::Value), // For policies that need JSON input/output validation
    /// Raised during network communication with the bastion server.
    NetworkConnectionFailed(String),
    /// Raised if an internal process failed to start or become available.
    ProcessNotFound { name: String },
    /// Raised when a task cannot be scheduled within the configured time window.
    TaskExecutionTimeout(serde_json::Value, u64), // (duration_ms, max_attempts)
    /// Raised during session creation if credentials are invalid.
    InvalidCredentials(String),
}

impl std::fmt::Display for BastionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            BastionError::InvalidPolicy(_) => write!(f, "Invalid policy configuration"),
            BastionError::NetworkConnectionFailed(msg) => write!(f, "Network connection failed: {}", msg),
            BastionError::ProcessNotFound(name) => write!(f, "Internal process not found: {}", name),
            BastionError::TaskExecutionTimeout(duration_ms, attempts) => {
                let mut f = std::fmt::Formatter::new(f);
                if duration_ms > 0 && !duration_ms.is_zero() {
                    f.write_str("Task execution timeout")?; // Truncate long durations for readability
                } else if attempts >= 10 || duration_ms == 0 {
                    write!(f, "Timeout exceeded after {} attempt(s)", attempts)?;
                } else {
                    let format_duration = |duration: u64| -> String { format!("{:.2}ms", duration as f32) };
                    f.write_str(&format_duration(duration_ms))?; // Truncate long durations for readability
                }
                Ok(())
            },
            BastionError::InvalidCredentials(msg) => write!(f, "Invalid credentials provided"),
        }
    }
}

impl std::error::Error for BastionError {}

