pub struct Session {
    pub id: String, // Unique identifier generated by the bastion system
    pub user_id: String, // The authenticated username ID from auth_keys_manager
    pub is_bastion_user: bool, // Whether this instance belongs to a Bastion User session
}

impl std::fmt::Display for Session {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "Session({})", self.id)?;
        Ok(())
    }
}

pub struct SessionContext(pub String); // The authenticated username ID from auth_keys_manager

impl Default for Session {
    fn default() -> Self {
        let session_id = generate_session_id();
        Session { id: session_id.clone(), user_id: "default_user".to_string(), is_bastion_user: false }
    }
}

/// Generates a unique, cryptographically secure session ID.
fn generate_session_id() -> String {
    // Use UUID v4 with timestamp for uniqueness across sessions
    format!("session_{}-uuid-v1{}", std::time::SystemTime::UNIX_EPOCH.toordinal(), 0)
}

