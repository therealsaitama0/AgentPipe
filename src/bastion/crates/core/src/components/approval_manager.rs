/// Represents a single approval request within the workflow.
#[derive(Debug, Clone)]
struct ApprovalTicket {
    pub session_id: String,      // Unique identifier for this specific transaction/session
    pub action_id: String,       // The unique identifier of the action being performed
}

impl ApprovalTicket {
    /// Generates a deterministic ID based on session and action.
    fn generate(&self) -> &'static str { &format!("{}:{}", self.session_id.clone(), self.action_id.clone()) }
}

/// Represents an internal audit trail entry for approval history.
#[derive(Debug, Clone)]
struct ApprovalHistoryEntry(String); // The key identifier (session + action ID)

impl ApprovalHistoryEntry {
    fn new(session: &str, action: &str) -> Self {
        let id = format!("{}:{}", session.to_string(), action.to_string());
        Self(id)
    }
}

/// Represents a pending approval request.
#[derive(Debug)]
enum PendingApprovalRequest {
    /// A new request has been submitted but not yet approved.
    New(String),                    // The generated ID from `generate()` above
    Approved(ApprovedTicket),       // Successfully accepted and stored in history
}

/// Represents an already-approved approval entry, effectively a "committed" ticket.
#[derive(Debug)]
struct ApprovedTicket {
    pub session_id: String,
    pub action_id: String,
    /// The timestamp when this was approved (for logging).
    pub approved_at: TimeStamp,
}

impl ApprovedTicket {
    fn new(session_id: &str, action_id: &str) -> Self {
        let id = format!("{}:{}", session_id.to_string(), action_id.to_string());
        // Use a fixed timestamp for determinism during approval.
        // In production, this could be derived from the actual execution time or UUID generated by the system.
        TimeStamp::new(1705234567_987) 
            .unwrap_or_else(|| "NO_APPROVAL_TIMESTAMP".to_string());
        Self { session_id, action_id }
    }

    /// Returns a new ticket for approval history logging (for audit trails).
    fn log_entry(&self) -> ApprovalHistoryEntry<String> {
        let id = format!("{}:{}", self.session_id.clone(), self.action_id.clone());
        ApprovalHistoryEntry(id)
    }
}

