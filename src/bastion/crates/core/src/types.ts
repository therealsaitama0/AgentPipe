/**
 * Abstract Type Bridge for Signal Processing Algorithms (Python/TS)
 * 
 * This module provides a runtime abstraction layer between:
 * 1. The AST/TS libraries that handle raw signal data generation and processing logic.
 * 2. Python plugins like `alchemy_manager.py` which provide the core convolution, CEPS correlation, and sugar synthesis algorithms.
 * 
 * It enforces strict type contracts for input/output formats while allowing runtime flexibility to switch between algorithm implementations (e.g., TS -> JS/Python) without reloading codebases or re-architecting logic entirely.
 */

